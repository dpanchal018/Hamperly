#!/usr/bin/env node
/**
 * scripts/generate-qa-report.js
 * 
 * Reads the Playwright JSON results file and generates:
 *   1. A Markdown QA Report document  →  validation-reports/live-site/qa-report.md
 *   2. GitHub Actions Job Summary     →  appended to $GITHUB_STEP_SUMMARY
 */

const fs = require('fs');
const path = require('path');

const JSON_PATH = path.join('validation-reports', 'live-site', 'results.json');
const REPORT_PATH = path.join('validation-reports', 'live-site', 'qa-report.md');

if (!fs.existsSync(JSON_PATH)) {
  console.error(`❌ Results file not found at ${JSON_PATH}`);
  process.exit(1);
}

const data = JSON.parse(fs.readFileSync(JSON_PATH, 'utf-8'));

// ─── Parse results ────────────────────────────────────────────────────────────
const runDate = new Date().toUTCString();
const stats = data.stats || {};
const totalTests = stats.expected ?? 0;
const passed    = stats.expected - (stats.unexpected ?? 0) - (stats.flaky ?? 0);
const failed    = stats.unexpected ?? 0;
const flaky     = stats.flaky ?? 0;
const skipped   = stats.skipped ?? 0;
const duration  = ((stats.duration ?? 0) / 1000).toFixed(1);

const overallStatus = failed > 0 ? '🔴 FAILED' : (flaky > 0 ? '🟡 FLAKY' : '🟢 PASSED');

// ─── Build per-test table rows ────────────────────────────────────────────────
function statusEmoji(status, outcome) {
  if (outcome === 'flaky') return '🟡 Flaky';
  if (status === 'passed')  return '🟢 Passed';
  if (status === 'failed')  return '🔴 Failed';
  if (status === 'skipped') return '⏭️ Skipped';
  return '⚪ Unknown';
}

const rows = [];
for (const suite of (data.suites || [])) {
  for (const spec of (suite.specs || [])) {
    // A spec can have multiple runs (retries)
    const results = spec.tests?.[0]?.results ?? [];
    const lastResult = results[results.length - 1];
    const outcome = spec.tests?.[0]?.status ?? 'unknown'; // passed / failed / flaky / skipped

    const durationMs = results.reduce((sum, r) => sum + (r.duration ?? 0), 0);
    const durationSec = (durationMs / 1000).toFixed(1);

    const errors = results
      .flatMap(r => r.errors ?? [])
      .map(e => (e.message ?? '').split('\n')[0].replace(/\|/g, '\\|').substring(0, 120))
      .filter(Boolean);

    rows.push({
      suite: suite.title,
      title: spec.title,
      outcome,
      durationSec,
      retries: results.length - 1,
      errors,
    });
  }
}

// ─── Generate Markdown ────────────────────────────────────────────────────────
function buildMarkdown(isGitHubSummary = false) {
  const lines = [];

  lines.push(`# 🕷️ Hamperly Live Site QA Report`);
  lines.push(``);
  lines.push(`> **Run Date:** ${runDate}`);
  lines.push(`> **Site:** https://hamperly.vercel.app`);
  lines.push(`> **Overall Status:** ${overallStatus}`);
  lines.push(``);

  // Summary table
  lines.push(`## Summary`);
  lines.push(``);
  lines.push(`| Metric | Value |`);
  lines.push(`|--------|-------|`);
  lines.push(`| ✅ Passed  | ${passed} |`);
  lines.push(`| 🔴 Failed  | ${failed} |`);
  lines.push(`| 🟡 Flaky   | ${flaky} |`);
  lines.push(`| ⏭️ Skipped  | ${skipped} |`);
  lines.push(`| ⏱️ Duration | ${duration}s |`);
  lines.push(``);

  // Per-test results
  lines.push(`## Test Results`);
  lines.push(``);
  lines.push(`| Status | Suite | Test | Duration | Retries |`);
  lines.push(`|--------|-------|------|----------|---------|`);

  for (const row of rows) {
    const emoji = statusEmoji(row.outcome, row.outcome);
    lines.push(`| ${emoji} | ${row.suite} | ${row.title} | ${row.durationSec}s | ${row.retries} |`);
  }

  lines.push(``);

  // Failures detail
  const failures = rows.filter(r => r.outcome === 'failed' || r.outcome === 'flaky');
  if (failures.length > 0) {
    lines.push(`## ❌ Failure Details`);
    lines.push(``);
    for (const row of failures) {
      lines.push(`### ${row.outcome === 'flaky' ? '🟡' : '🔴'} ${row.title}`);
      lines.push(`**Suite:** ${row.suite}  `);
      lines.push(`**Retries:** ${row.retries}  `);
      if (row.errors.length > 0) {
        lines.push(``);
        lines.push(`**Error messages:**`);
        lines.push(`\`\`\``);
        for (const e of row.errors) {
          lines.push(e);
        }
        lines.push(`\`\`\``);
      }
      lines.push(``);
    }
  } else {
    lines.push(`## ✅ All Tests Passed`);
    lines.push(``);
    lines.push(`No failures or issues detected on the live site.`);
    lines.push(``);
  }

  lines.push(`---`);
  lines.push(`*Report generated by Hamperly automated QA pipeline*`);

  return lines.join('\n');
}

const markdown = buildMarkdown(false);

// ─── Write Markdown report ────────────────────────────────────────────────────
fs.mkdirSync(path.dirname(REPORT_PATH), { recursive: true });
fs.writeFileSync(REPORT_PATH, markdown, 'utf-8');
console.log(`✅ QA report written to ${REPORT_PATH}`);

// ─── Append to GitHub Actions Job Summary ────────────────────────────────────
const summaryPath = process.env.GITHUB_STEP_SUMMARY;
if (summaryPath) {
  fs.appendFileSync(summaryPath, '\n' + markdown + '\n');
  console.log(`✅ Report posted to GitHub Actions Job Summary`);
}
